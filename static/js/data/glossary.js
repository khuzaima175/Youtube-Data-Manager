// Aliases and shorthand pointers for universal backward-compatibility
window.GLOSSARY = new Proxy(_GLOSSARY_CORE, {
  get(target, prop) {
    if (typeof prop !== 'string') return undefined;
    if (prop in target) return target[prop];
    const snake = prop.replace(/([A-Z])/g, '_$1').toLowerCase();
    if (snake in target) return target[snake];
    const camel = prop.replace(/_([a-z])/g, (_, l) => l.toUpperCase());
    if (camel in target) return target[camel];
    return undefined;
  }
});
